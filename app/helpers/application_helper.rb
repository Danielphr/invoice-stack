  # A link is active on its own page and on any page nested under it, so
  # "Clients" stays highlighted on /clients/1/edit.
  def nav_link_to(name, path, icon:)
    active = current_page?(path) || request.path.start_with?("#{path}/")

    link_to path,
      class: class_names(
        "flex items-center gap-x-3 rounded-md px-3 py-2 text-sm font-semibold",
        active ? "bg-navy-800 text-white" : "text-navy-300 hover:bg-navy-800 hover:text-white"
      ),
      aria: { current: ("page" if active) } do
      safe_join([ nav_icon(icon, active:), name ])
    end
  end

  private
    def nav_icon(name, active:)
      tag.svg(class: [ "size-6 shrink-0", ("text-brand-300" if active) ], fill: "none", viewBox: "0 0 24 24", "stroke-width": "1.5",
        stroke: "currentColor", aria: { hidden: true }) do
        tag.path("stroke-linecap": "round", "stroke-linejoin": "round", d: NAV_ICONS.fetch(name))
      end
    end
